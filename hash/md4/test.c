void print_error(uint8_t* digest, uint8_t* expected_digest);

int main(int argc, char* argv[]) {
    uint8_t* digest = NULL;
    int status = 0;
    
    for (size_t i = 0; i < NUM_TEST; i++) {
        digest = md4(inputs[i], inputs_length[i]);

        status = 0;
        for (size_t j = 0; j < HASH_SIZE; j++) {
            if (digest[j] != spected_outputs[i][j]) {
                status = 1;
                break;
            }
        }

        if (status == 0) {
            printf("[SUCCESS] Test %zu\n", i + 1);
        } else {
            printf("[FAILED] Test %zu\n", i + 1);
            print_error(digest, spected_outputs[i]);
        }

        free(digest);
    }
}

void print_error(uint8_t* digest, uint8_t* expected_digest) {
    printf("\t");
    for (size_t i = 0; i < HASH_SIZE; i++) {
        printf("%02X ", digest[i]);
    }
    printf("\n\t");
    for (size_t i = 0; i < HASH_SIZE; i++) {
        printf("%02X ", expected_digest[i]);
    }
    printf("\n");
}
